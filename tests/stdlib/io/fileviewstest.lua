require("nupp.runtime.standardio")
local test = require("assert")
local span = require("binary.span")
local views = require("io.internal.fileviews")
local M = {}

-- Byte views share their Lua file's cursor, so they need a file that seeks.
local function requireseek()
    local path = os.tmpname()
    local probe = assert(io.open(path, "w+b"))
    local seekable = type(probe.seek) == "function"
    probe:close()
    os.remove(path)
    test.suite.requirecapability("io.file.seek", seekable)
end

local function withFile(text, body)
    requireseek()
    local path = os.tmpname()
    local file = assert(io.open(path, "w+b"))
    local ok, problem = pcall(function()
        assert(file:write(text))
        assert(file:flush())
        assert(file:seek("set", 0))
        body(file)
    end)
    if io.type(file) == "file" then
        file:close()
    end
    os.remove(path)
    if not ok then
        error(problem, 0)
    end
end

function M.nativeHandlesKeepLuaMethodsAndOneCursorAcrossViews()
    withFile("abcdef", function(file)
        test.eq(type(file), "userdata")
        test.eq(io.type(file), "file")
        local rawRead = getmetatable(file).__index.read
        local reader = file:reader()
        test.eq(reader:read(2), "ab")
        test.eq(rawRead(file, 2), "cd")
        test.eq(reader:read(9), "ef")
        test.eq(reader:read(1), "")
        test.eq(rawRead(file, 1), nil)
        assert(file:seek("set", 0))
        local writer = file:writer()
        assert(writer:write("XY"))
        assert(writer:flush())
        test.eq(file:seek(), 2)
        test.eq(rawRead(file, 2), "cd")
        writer:close()
        test.eq(io.type(file), "file")
        test.eq(reader:read(2), "ef")
        reader:close()
        test.eq(io.type(file), "file")
        assert(file:seek("set", 0))
        test.eq(rawRead(file, "*a"), "XYcdef")
    end)
end

function M.spanAndBufferReadsShareTheNativeCursorAndPreserveOtherBytes()
    withFile("abcdefghi", function(file)
        local reader = views.reader(file)
        local storage = io.Buffer.create(4)
        local lease = storage:reservewrite(4, 4)
        test.eq(reader:readspan(lease:span()), 4)
        lease:commit(4)
        test.eq(storage:getstring(), "abcd")
        storage:close()
        local destination = io.Buffer.create("--------")
        test.eq(reader:readinto(destination, 2, 3), 3)
        test.eq(destination:tostring(), "--efg---")
        test.eq(reader:readinto(destination, 0, 5), 2)
        test.eq(destination:tostring(), "hiefg---")
        test.eq(reader:readinto(destination, 0, 1), 0)
        test.eq(destination:tostring(), "hiefg---")
        reader:close()
        destination:close()
    end)
end

function M.spanWritesAndTransfersUseTheSameFileAndByteContracts()
    withFile("", function(destination)
        local writer = views.writer(destination)
        test.eq(writer:writespan(span.fromstring("prefix:")), 7)
        local empty = span.fromstring("")
        test.eq(writer:writespan(empty), 0)
        withFile(string.rep("payload", 12000), function(source)
            local reader = views.reader(source)
            test.eq(reader:transferto(writer), 84000)
            test.eq(reader:read(1), "")
            reader:close()
        end)
        assert(writer:flush())
        writer:close()
        test.eq(io.type(destination), "file")
        assert(destination:seek("set", 0))
        test.eq(destination:read("*a"), "prefix:" .. string.rep("payload", 12000))
    end)
end

function M.closingEitherViewLeavesItsParentAndSiblingOpen()
    withFile("abc", function(file)
        local reader = views.reader(file)
        local writer = views.writer(file)
        reader:close()
        local value, reason = reader:read(1)
        test.eq(value, nil)
        test.eq(reason, "the reader is closed")
        test.eq(io.type(file), "file")
        assert(writer:write("Z"))
        assert(writer:flush())
        writer:close()
        local wrote, failure = writer:write("ignored")
        test.eq(wrote, false)
        test.eq(failure, "the writer is closed")
        test.eq(io.type(file), "file")
        assert(file:seek("set", 0))
        test.eq(file:read("*a"), "Zbc")
    end)
end

function M.anOwnedWriterTakesItsFileAndClosesIt()
    local path = os.tmpname()
    local file = assert(io.open(path, "wb"))
    local writer = views.ownedwriter(file)
    assert(writer:write("owned"))
    assert(writer:flush())
    test.eq(io.type(file), "file", "writing leaves the file open")
    writer:close()
    test.eq(io.type(file), "closed file", "closing the writer closes the file it took")
    writer:close()
    local check = assert(io.open(path, "rb"))
    test.eq(check:read("*a"), "owned")
    check:close()
    os.remove(path)

    local borrowedFile = assert(io.open(path, "wb"))
    local borrowed = views.writer(borrowedFile)
    borrowed:close()
    test.eq(io.type(borrowedFile), "file", "a borrowed view leaves its file open")
    borrowedFile:close()
    os.remove(path)
end

function M.closedParentsReturnByteErrorsRatherThanLuaClosedFileRaises()
    withFile("abc", function(file)
        local reader = views.reader(file)
        local writer = views.writer(file)
        assert(file:close())
        test.eq(reader:isreleased(), true)
        test.eq(writer:isreleased(), true)
        local value, reason = reader:read(1)
        test.eq(value, nil)
        test.eq(reason, "the file is closed")
        local wrote, failure = writer:write("ignored")
        test.eq(wrote, false)
        test.eq(failure, "the file is closed")
        local flushed, flushFailure = writer:flush()
        test.eq(flushed, false)
        test.eq(flushFailure, "the file is closed")
        reader:close()
        writer:close()
    end)
end

function M.aHeldViewKeepsItsNativeParentAliveAcrossCollection()
    requireseek()
    local path = os.tmpname()
    local weak = setmetatable({}, {__mode = "v"})
    local reader
    local ok, problem = pcall(function()
        local file = assert(io.open(path, "w+b"))
        assert(file:write("retained"))
        assert(file:seek("set", 0))
        weak[1] = file
        reader = views.reader(file)
        file = nil
        collectgarbage("collect")
        collectgarbage("collect")
        assert(weak[1], "the reader must retain its parent file")
        test.eq(io.type(weak[1]), "file")
        test.eq(reader:read(8), "retained")
        reader:close()
        reader = nil
        collectgarbage("collect")
        collectgarbage("collect")
        test.eq(weak[1], nil)
    end)
    if weak[1] and io.type(weak[1]) == "file" then
        weak[1]:close()
    end
    os.remove(path)
    if not ok then
        error(problem, 0)
    end
end

function M.boundedLinesOwnOnlyTheViewAndKeepTheFileUsable()
    withFile("one\r\n\nlast", function(file)
        local lines = views.reader(file):lines(4)
        test.eq(lines:read(), "one")
        test.eq(lines:read(), "")
        test.eq(lines:read(), "last")
        local value, reason = lines:read()
        test.eq(value, nil)
        test.eq(reason, nil)
        lines:close()
        test.eq(io.type(file), "file")
        assert(file:seek("set", 0))
        test.eq(file:read("*l"), "one\r")
    end)
    withFile("oversized\n", function(file)
        local lines = views.reader(file):lines(4)
        local value, reason = lines:read()
        test.eq(value, nil)
        test.eq(reason, "a line was longer than the limit")
        lines:close()
        test.eq(io.type(file), "file")
    end)
end

return M
