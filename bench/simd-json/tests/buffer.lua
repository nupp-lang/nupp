require("compiled")()
local production = require("production_json_test")
require("simdjson_bench")
local native = require("simdjson_bench_native")
local Buffer = require("bytes").Buffer
local source = production.source()
local input = Buffer.create("skip" .. source)
input:skip(4)
assert(production.preparedBufferDecode(input).id == 41)
assert(production.preparedBufferCopyDecode(input).id == 41)
local schema = native.compileSerde(production.controlPlan(), "reject")
local decoded, problem = native.decodeSerdeBuffer(schema, input)
assert(decoded and decoded.child.label == "one", problem)
assert(input:tostring() == source and #input == #source)
input:close()

local out = Buffer.create("prefix:")
local writer = native.writer(out)
writer:startObject():key("items"):startArray()
for index = 1, 20000 do
    writer:write(index)
end
writer:endArray():endObject()
writer:close()
local encoded = out:tostring()
assert(encoded:sub(1, 7) == "prefix:")
local value = native.decode(encoded:sub(8))
assert(#value.items == 20000 and value.items[1] == 1 and value.items[20000] == 20000)
out:close()
print("buffer clients passed")
