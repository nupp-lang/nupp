// Opaque linked symbol addresses; calls retain their original signatures.
// Foreign statics name addresses only. No instruction byte is read as data.
macro_rules! core_symbols {
    ($($name:ident,)*) => {
        pub const CORE_EXPORT_NAMES: &[&str] = &[$(stringify!($name)),*];
        unsafe extern "C" { $(static $name: u8;)* }
        fn linked_addresses() -> [usize; CORE_EXPORT_COUNT] {
            [$(std::ptr::addr_of!($name) as usize),*]
        }
    };
}
