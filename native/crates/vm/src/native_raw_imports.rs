// Existing frozen host services, addressed without signature or opcode policy.
macro_rules! host_imports {
    ($($name:ident => $path:path,)*) => {
        pub const HOST_IMPORT_NAMES: &[&str] = &[$(stringify!($name)),*];
        pub fn host_symbol(name: &str) -> Option<usize> {
            Some(match name {
                $(stringify!($name) => $path as *const () as usize,)*
                _ => return None,
            })
        }
    };
}
